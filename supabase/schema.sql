-- Ananna Birthday Experience — Supabase schema
-- Run once in: Supabase Dashboard → SQL Editor → New query

create table if not exists public.wishes (
  id         bigint generated by default as identity primary key,
  sender     text        not null check (char_length(sender)  between 1 and 40),
  message    text        not null check (char_length(message) between 1 and 240),
  created_at timestamptz not null default now()
);

create index if not exists wishes_created_at_idx on public.wishes (created_at desc);

alter table public.wishes enable row level security;

-- Public read
drop policy if exists "Anyone can view birthday wishes" on public.wishes;
create policy "Anyone can view birthday wishes"
  on public.wishes for select to anon using (true);

-- Public insert (length-checked server-side; no UPDATE/DELETE policies = denied)
drop policy if exists "Anyone can submit birthday wishes" on public.wishes;
create policy "Anyone can submit birthday wishes"
  on public.wishes for insert to anon
  with check (
    char_length(sender)  between 1 and 40
    and char_length(message) between 1 and 240
  );

